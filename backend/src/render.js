import fs from 'node:fs';
import path from 'node:path';
import { getSetting, setSetting } from './settings.js';

const RENDER_DIR = process.env.RENDER_DIR || '/rendered';
const RELAY_DATA = '/data/relay';

// The ICE servers the relay hands to clients so their WebRTC stack can find
// a path (plan sections 8.3 and 9). TURN credentials are visible to every
// logged-in user by design — it is a private group; rotate when someone
// leaves.
export function relayIceServers() {
  const ip = getSetting('turn.public_ip') || process.env.PUBLIC_IP;
  const user = getSetting('turn.username');
  const pass = getSetting('turn.password');
  const list = [
    { type: 'stun', address: 'stun.l.google.com:19302' },
    { type: 'stun', address: 'stun1.l.google.com:19302' },
  ];
  if (pass) {
    list.push({ type: 'turn', address: `${ip}:3478`, username: user, password: pass });
    list.push({ type: 'turn', address: `${ip}:5349`, username: user, password: pass });
  }
  return list;
}

export function relayConfig() {
  const ip = getSetting('turn.public_ip') || process.env.PUBLIC_IP;
  return {
    debug: false,
    server: {
      comment: 'private relay',
      show_local_worlds: true,
      ip_forwarding: {
        enabled: true,
        headers: ['X-Forwarded-For'],
      },
      origin_whitelist: {
        enabled: true,
        hostnames: [`https://${ip}`],
      },
    },
    relays: relayIceServers(),
  };
}

// Rendered to the relay's mounted data dir; takes effect on relay restart.
export function writeRelayConfig() {
  fs.mkdirSync(RELAY_DATA, { recursive: true });
  const file = path.join(RELAY_DATA, 'relay-config.json');
  fs.writeFileSync(file, JSON.stringify(relayConfig(), null, 2) + '\n');
  return file;
}

export function turnServerConf() {
  const ip = getSetting('turn.public_ip') || process.env.PUBLIC_IP;
  // Oracle VMs are NATted: with the private address known, coturn can map
  // the public relay address correctly (plan section 9.3).
  const priv = process.env.PRIVATE_IP;
  const external = priv ? `external-ip=${ip}/${priv}` : `external-ip=${ip}`;
  const user = getSetting('turn.username');
  const pass = getSetting('turn.password');
  const cert = '/etc/coturn-certs/fullchain.pem';
  const key = '/etc/coturn-certs/privkey.pem';
  const hasCerts = fs.existsSync('/tls/nginx/fullchain.pem');
  return `# Generated by the eagler backend — edit via the admin page, not here.
listening-port=3478
${hasCerts ? `tls-listening-port=5349\ncert=${cert}\npkey=${key}` : '# TLS port disabled until a certificate exists'}
${external}
min-port=49160
max-port=49200
fingerprint
lt-cred-mech
realm=${ip}
user=${user}:${pass}
no-multicast-peers
no-cli
no-tlsv1
no-tlsv1_1
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.168.0.0-192.168.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
total-quota=20
bps-capacity=0
`;
}

export function writeTurnConfig() {
  fs.mkdirSync(path.join(RENDER_DIR, 'coturn'), { recursive: true });
  const file = path.join(RENDER_DIR, 'coturn', 'turnserver.conf');
  fs.writeFileSync(file, turnServerConf());
  return file;
}

// Called by start.sh (through the bootstrap endpoint) and whenever the admin
// changes TURN or relay settings. Takes effect after `./eaglerctl restart relay coturn`.
export function renderNetworkConfigs() {
  writeRelayConfig();
  writeTurnConfig();
}
